/// 渲染一个图标（内联 `<svg>`，`fill` 交给 CSS 的 `currentColor`）。
pub fn icon(icon: Icon) -> AnyView {
    let view_box = icon.view_box();
    let paths = icon.paths();
    view! {
        <svg
            viewBox=view_box
            focusable="false"
            aria-hidden="true"
            fill="currentColor"
            class="icon"
        >
            {paths.iter().map(|d| view! { <path d=*d></path> }).collect_view()}
        </svg>
    }
    .into_any()
}
